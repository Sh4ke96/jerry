/** Repo-relative glob patterns, forward slashes, e.g. "src/**". */
export const planScopeSchema = z.array(z.string().min(1)).min(1);

const text = z.string().trim().min(1);

/**
 * The plan document (spec §7.2, Phase 3, the 18 sections). Claude drafts it with the /jerry:plan
 * skill and submits it through MCP; the user approves exactly this document (its hash). The
 * sections that make a plan reviewable are required; the rest may be empty lists.
 */
export const planDocumentSchema = z.object({
  /** 1. Goal of the task. */
  goal: text,
  /** 2. Classification. */
  classification: z.array(z.enum(['ui-ux', 'frontend', 'api-backend', 'database', 'infrastructure', 'security', 'docs', 'tests', 'refactoring', 'tooling'])).min(1),
  /** 3. Repositories the change touches (absolute paths). */
  repositories: z.array(text).min(1),
  /** 4. Current state and discovery findings; unknowns are written as UNKNOWN, never guessed. */
  currentState: text,
  /** 5. Proposed changes. */
  changes: z.array(z.object({ kind: z.enum(['add', 'change', 'remove']), target: text, description: text })).min(1),
  /** 6. Impact on architecture and modules. */
  architectureImpact: text,
  /** 7. Dependencies and contracts between repositories. */
  crossRepoDependencies: z.string().default(''),
  /** 8. Risks, security, compatibility. */
  risks: z.array(z.object({ risk: text, severity: z.enum(['low', 'medium', 'high']), mitigation: text })).default([]),
  /** 8. Rollback. */
  rollback: z.string().default(''),
  /** 9. Files and areas in scope (repo-relative globs; this is what JERRY checks edits against) and out of scope. */
  scope: z.object({ include: planScopeSchema, exclude: z.array(text).default([]) }),
  /** 10 and 11. Implementation steps, with their order and dependencies. */
  steps: z.array(z.object({ step: text, files: z.array(text).default([]), dependsOn: z.array(z.number().int().positive()).default([]) })).min(1),
  /** 12. Tests to add or run. */
  tests: z.array(z.object({ kind: z.enum(['unit', 'component', 'integration', 'api', 'e2e', 'manual']), description: text })).min(1),
  /** 13. Regression plan. */
  regression: z.string().default(''),
  /** 14. Proposed commit subjects, per repository; JERRY never commits. */
  commitSubjects: z.array(text).default([]),
  /** 15. QA handover scenarios for a manual tester. */
  qaScenarios: z.array(z.object({ title: text, steps: z.array(text).min(1), expected: text })).default([]),
  /** 16. Optional artifact, demo or presentation. */
  artifact: z.string().default(''),
  /** 17. Definition of Done. */
  definitionOfDone: z.array(text).min(1),
  /** 18. Unresolved questions and decisions for the user. */
  openQuestions: z.array(text).default([]),
  /**
   * The analysis the plan is built on (ADR 0024): the IDs of the analysts' reports it uses and the
   * gaps they left. Optional and without a default, so plans submitted before it keep their hash.
   */
  analysis: z.object({ reports: z.array(z.number().int().positive()), gaps: z.array(text).default([]) }).optional(),
});
export type PlanDocument = z.infer<typeof planDocumentSchema>;

export const planSchema = z.object({
  version: z.number().int().positive(),
  contentHash: contentHashSchema,
  scope: planScopeSchema,
  createdAt: z.iso.datetime(),
  /** The full plan when Claude submitted one; plans created with only a scope (CLI) have none. */
  document: planDocumentSchema.optional(),
});
export type Plan = z.infer<typeof planSchema>;

/** A manual QA scenario (spec §15.1). */
export const qaScenarioSchema = z.object({
  id: text,
  priority: z.enum(['P1', 'P2', 'P3']),
  title: text,
  /** Module and exact location: UI path, screen, endpoint or command. */
  location: text,
  roles: z.array(text).default([]),
  preconditions: z.string().default(''),
  testData: z.string().default(''),
  steps: z.array(text).min(1),
  expected: text,
  /** What must not happen, or the negative variant to try. */
  negative: z.string().default(''),
  /** Related API calls or events, if any. */
  related: z.string().default(''),
  kind: z.enum(['new', 'regression']),
});
export type QaScenario = z.infer<typeof qaScenarioSchema>;

/**
 * Claude's implementation report (spec §7.2 Phase 5). Results are reported as they were, never
 * assumed: a check that did not run is NOT_RUN with the reason, never PASS (spec §19).
 */
export const implementationReportSchema = z.object({
  /** What was done, in a few sentences. */
  summary: text,
  /** What actually changed: repo-relative paths per repository. */
  changes: z.array(z.object({ repository: z.string().default(''), path: text, kind: z.enum(['added', 'modified', 'deleted', 'renamed']), description: text })).min(1),
  /** Work done by each agent or subagent, when more than one took part. */
  agents: z.array(z.object({ agent: text, work: text })).default([]),
  /** Skills that were required and whether they were used. */
  skills: z.array(z.object({ name: text, used: z.boolean(), note: z.string().default('') })).default([]),
  /** Tests, build, lint and typecheck with their real results. */
  checks: z
    .array(
      z
        .object({ kind: z.enum(['test', 'build', 'lint', 'typecheck', 'other']), command: text, result: z.enum(['PASS', 'FAIL', 'NOT_RUN']), details: z.string().default('') })
        .refine((check) => check.result !== 'NOT_RUN' || check.details.trim() !== '', { message: 'a check that did not run needs the reason in details', path: ['details'] }),
    )
    .min(1),
  /** Differences from the approved plan, with the reason for each. */
  planDeviations: z.array(z.object({ description: text, reason: text })).default([]),
  /** Findings and unresolved risks. */
  risks: z.array(z.object({ risk: text, severity: z.enum(['low', 'medium', 'high', 'critical']), mitigation: z.string().default('') })).default([]),
  /** Proposed commit subjects in the repository's convention; the user commits. */
  commitSubjects: z.array(text).min(1),
  qaScenarios: z.array(qaScenarioSchema).min(1),
  /** Optional artifact (demo, presentation); never written into the repository. */
  artifact: z.string().default(''),
});
export type ImplementationReport = z.infer<typeof implementationReportSchema>;

/**
 * What JERRY itself recorded between the plan approval and the report: the report's claims are
 * shown next to these facts. Shell commands can change files without JERRY seeing which, so
 * observed edits cover the file tools only.
 */
export const reportEvidenceSchema = z.object({
  since: z.iso.datetime(),
  deviations: z.array(z.object({ at: z.iso.datetime(), tool: z.string().nullable(), target: z.string().nullable(), rule: z.string().nullable() })),
  deviationCount: z.number().int().nonnegative(),
  blockedCount: z.number().int().nonnegative(),
  /** Repo-relative paths edited with the file tools (Write, Edit, MultiEdit, NotebookEdit). */
  observedEdits: z.array(z.string()),
  /** Observed edits the report does not mention. */
  unreportedEdits: z.array(z.string()),
  /** Checks the report marks FAIL or NOT_RUN. */
  failedOrNotRunChecks: z.number().int().nonnegative(),
  /**
   * What Git shows since the plan's baseline (ADR 0017), including changes made by shell commands.
   * Files the user had changed before approval count only if their content changed again. Null
   * when Git could not be read; absent in reports made before M3.
   */
  git: z
    .object({
      baselineHead: z.string().nullable(),
      baselineAt: z.iso.datetime().nullable(),
      changed: z.array(z.string()),
      /** Files with the user's uncommitted changes at baseline that changed again. */
      userChanged: z.array(z.string()),
    })
    .nullable()
    .default(null),
  /**
   * Continuous quality at the time of the report (ADR 0027–0031): open findings, the test runs
   * JERRY saw against what the report claims, and plan drift. Absent in reports made before M5.
   */
  quality: z
    .object({
      openFindings: z.number().int().nonnegative(),
      /** Open P1 and P2 findings: "FND-3 P1 src/a.ts:12 Secret written into the code". */
      serious: z.array(z.string()),
      /** The latest test run JERRY saw for the task. */
      lastTestRun: z.object({ command: z.string(), result: z.enum(['PASS', 'FAIL', 'INTERRUPTED']), summary: z.string().nullable(), at: z.iso.datetime() }).nullable(),
      /** Checks the report marks PASS that JERRY saw end otherwise ("npm test: JERRY saw FAIL at …"). */
      claimedVsObserved: z.array(z.string()),
      /** Changed files no plan step names, and steps not started. */
      unplannedFiles: z.array(z.string()),
      untouchedSteps: z.array(z.string()),
    })
    .optional(),
});
export type ReportEvidence = z.infer<typeof reportEvidenceSchema>;

