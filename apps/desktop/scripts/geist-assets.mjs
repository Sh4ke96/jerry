// Builds Jerry's Geist assets from the pinned Fontsource packages (SIL Open Font License 1.1):
//   ui/fonts/                               Geist and Geist Mono (variable, Latin subset) with their OFL texts
//   src-tauri/icons/source/jerry-logo.svg   the logo: the Geist "J" as a plain SVG path on a rounded square
//   src-tauri/icons/                        the app icons, generated from the SVG with "tauri icon"
// Usage: node scripts/geist-assets.mjs [--weight 700|600]   (or: pnpm --filter @jerry/desktop icons)
// Geist Bold (700) is the default: it reads better than SemiBold at 16 and 32 px.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const opentype = require('opentype.js');

const desktop = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const modules = path.join(desktop, 'node_modules');
const weightIndex = process.argv.indexOf('--weight');
const weight = weightIndex === -1 ? '700' : process.argv[weightIndex + 1];
if (weight !== '700' && weight !== '600') throw new Error('--weight must be 700 (Bold) or 600 (SemiBold)');

// 1. Fonts for the local pages.
const fontsDir = path.join(desktop, 'ui', 'fonts');
fs.mkdirSync(fontsDir, { recursive: true });
const copies = [
  ['@fontsource-variable/geist/files/geist-latin-wght-normal.woff2', 'Geist-Latin-Variable.woff2'],
  ['@fontsource-variable/geist-mono/files/geist-mono-latin-wght-normal.woff2', 'GeistMono-Latin-Variable.woff2'],
  ['@fontsource-variable/geist/LICENSE', 'OFL.txt'],
  ['@fontsource-variable/geist-mono/LICENSE', 'OFL-GeistMono.txt'],
];
for (const [from, to] of copies) {
  fs.copyFileSync(path.join(modules, from), path.join(fontsDir, to));
  console.log(`geist-assets: ui/fonts/${to}`);
}

// 2. The logo: the Geist "J" outline, scaled and centred on the 1024 x 1024 rounded square.
const SIZE = 1024;
const RADIUS = Math.round(SIZE * 0.22);
/** Height of the letter: large enough to read at 16 px, with room around it. */
const LETTER_HEIGHT = 600;
const fontFile = path.join(modules, '@fontsource', 'geist', 'files', `geist-latin-${weight}-normal.woff`);
const data = fs.readFileSync(fontFile);
const font = opentype.parse(data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength));
const glyph = font.charToGlyph('J');
const unit = glyph.getPath(0, 0, 1000).getBoundingBox();
const scale = LETTER_HEIGHT / (unit.y2 - unit.y1);
const outline = glyph.getPath(0, 0, 1000 * scale);
const box = outline.getBoundingBox();
// Optical centring: the bounding box is centred, then the J's heavy stem sits a little right of
// the middle and its open hook on the left, so it is nudged left by 2 % of the letter width.
const dx = (SIZE - (box.x2 - box.x1)) / 2 - box.x1 - (box.x2 - box.x1) * 0.02;
const dy = (SIZE - (box.y2 - box.y1)) / 2 - box.y1;
for (const command of outline.commands) {
  for (const [x, y] of [['x', 'y'], ['x1', 'y1'], ['x2', 'y2']]) {
    if (command[x] !== undefined) {
      command[x] += dx;
      command[y] += dy;
    }
  }
}
// Sanity check: the J's flat stem end is at the top (on-curve points at two x positions share
// the top edge) and its round hook at the bottom.
const onCurve = outline.commands.filter((command) => command.y !== undefined);
const top = Math.min(...onCurve.map((command) => command.y));
const xsAtTop = new Set(onCurve.filter((command) => Math.abs(command.y - top) < 0.5).map((command) => Math.round(command.x)));
if (xsAtTop.size < 2) throw new Error('the J came out upside down');
// getPath already has SVG's y axis. Serialised here rather than with toPathData, which in
// opentype.js 2 flips the y axis once more by default.
const n = (value) => String(Math.round(value * 10) / 10);
const pathData = outline.commands
  .map((c) => {
    switch (c.type) {
      case 'M':
      case 'L':
        return `${c.type}${n(c.x)} ${n(c.y)}`;
      case 'Q':
        return `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
      case 'C':
        return `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
      case 'Z':
        return 'Z';
      default:
        throw new Error(`unexpected path command ${c.type}`);
    }
  })
  .join('');
if (pathData.includes('NaN')) throw new Error('the glyph path has invalid coordinates');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
  <!-- Jerry logo: the "J" of Geist ${weight === '700' ? 'Bold' : 'SemiBold'} (SIL Open Font License 1.1) as a path, on a rounded square. Generated by apps/desktop/scripts/geist-assets.mjs. -->
  <rect width="${SIZE}" height="${SIZE}" rx="${RADIUS}" ry="${RADIUS}" fill="#09090b"/>
  <path d="${pathData}" fill="#fafafa"/>
</svg>
`;
const logo = path.join(desktop, 'src-tauri', 'icons', 'source', 'jerry-logo.svg');
fs.writeFileSync(logo, svg);
console.log(`geist-assets: src-tauri/icons/source/jerry-logo.svg (Geist ${weight}, letter box ${Math.round(box.x2 - box.x1)} x ${Math.round(box.y2 - box.y1)})`);

// 3. The app icons (window, taskbar, installer, tray) from the logo. Jerry is a Windows
// app: the mobile and Microsoft Store variants "tauri icon" also writes are removed.
const iconsDir = path.join(desktop, 'src-tauri', 'icons');
const tauri = spawnSync(process.execPath, [path.join(modules, '@tauri-apps', 'cli', 'tauri.js'), 'icon', logo, '--output', iconsDir], {
  cwd: desktop,
  stdio: 'inherit',
  windowsHide: true,
});
if (tauri.status !== 0) throw new Error('"tauri icon" failed');
for (const entry of fs.readdirSync(iconsDir)) {
  if (entry === 'android' || entry === 'ios' || /^Square\d+x\d+Logo\.png$/.test(entry) || entry === 'StoreLogo.png') {
    fs.rmSync(path.join(iconsDir, entry), { recursive: true, force: true });
  }
}
console.log(`geist-assets: src-tauri/icons/ ${fs.readdirSync(iconsDir).join(', ')}`);
